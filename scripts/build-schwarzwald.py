def ridge(base_fn, step, tooth_lo, tooth_hi, seed, bottom):
    """Forested ridge: smooth profile with spruce teeth along the crest."""
    rng = random.Random(seed)
    pts = []
    x = -6
    while x <= W + 6:
        y = base_fn(x)
        h = rng.uniform(tooth_lo, tooth_hi)
        pts.append((x, y - h))
        pts.append((x + step / 2, y - rng.uniform(0, tooth_lo * 0.35)))
        x += step
    d = [f"M-6 {bottom}", f"L{pts[0][0]:.1f} {pts[0][1]:.1f}"]
    for px, py in pts[1:]:
        d.append(f"L{px:.1f} {py:.1f}")
    d.append(f"L{W + 6} {bottom} Z")
    return " ".join(d)

def hump(cx, half_w, peak_y, base_y, step, tooth_lo, tooth_hi, seed, bottom):
    """Forested spur: a cosine hump with spruce teeth, used to hide the
    viaduct's ends in hillsides instead of leaving them floating."""
    rng = random.Random(seed)
    def prof(x):
        t = (x - cx) / half_w
        if abs(t) >= 1:
            return base_y
        return base_y - (base_y - peak_y) * (0.5 + 0.5 * math.cos(math.pi * t))
    x_start, x_end = cx - half_w, cx + half_w
    d = [f"M{x_start:.1f} {bottom}"]
    x = x_start
    while x <= x_end:
        y = prof(x)
        d.append(f"L{x:.1f} {y - rng.uniform(tooth_lo, tooth_hi):.1f}")
        d.append(f"L{x + step / 2:.1f} {y - rng.uniform(0, tooth_lo * 0.4):.1f}")
        x += step
    d.append(f"L{x_end:.1f} {bottom} Z")
    return " ".join(d)

