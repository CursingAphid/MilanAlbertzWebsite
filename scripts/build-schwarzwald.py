# ---- foreground: the shore we stand on, framed by dark spruces ----
def spruce(cx, base, top, half, tiers, fill):
    """Layered spruce silhouette."""
    parts = [f'    <rect x="{cx - 2.2:.1f}" y="{base - 8:.1f}" width="4.4" height="9" fill="{fill}"/>']
    span = base - top
    for i in range(tiers):
        t = i / tiers
        y_top = top + span * t * 0.62
        y_bot = top + span * (t * 0.62 + 0.42)
        w = half * (0.34 + 0.66 * (t + 0.32) / 1.32)
        parts.append(
            f'    <path d="M{cx:.1f} {y_top:.1f} L{cx + w:.1f} {y_bot:.1f} L{cx - w:.1f} {y_bot:.1f} Z" fill="{fill}"/>'
        )
    return "\n".join(parts)

